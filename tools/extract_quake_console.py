#!/usr/bin/env python3
"""Extract the real GLQuake console assets from a GOG/retail PAK0.PAK and
emit examples/quake_console.h for the quake.console testsuite cases.

Emits:
  g_quakePalette[768]      gfx/palette.lmp (RGB triples)
  g_quakeConchars[16384]   gfx.wad "conchars" lump (128x128 8-bit glyph atlas)
  g_quakeConback[64000]    gfx/conback.lmp pixel data (320x200 8-bit, after the
                           qpic_t {int w; int h} header)

The tests convert these exactly the way BlitzQuake's GL_Upload8 does:
  * conchars: every 0 index becomes 255 before expansion
    (gl_draw.c:487-489), then d_8to24table[...] gives RGB plus the palette
    alpha quirk 0xAA=170, with index 255 transparent
    (gl_vidamiga.c:239-246).
  * conback: same expansion without the 0->255 preprocess, then the game
    resamples 320x200 -> gl_max_size (256x256) via GL_ResampleTexture
    (gl_draw.c:1287).

Usage: python3 tools/extract_quake_console.py [path-to-PAK0.PAK] [out.h]
"""
import os
import struct
import sys
import zlib

DEFAULT_PAK = os.path.expanduser(
    "~/.wine/drive_c/GOG Games/Quake/id1/PAK0.PAK")
DEFAULT_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "..", "examples", "quake_console.h")


def read_pak(path):
    data = open(path, "rb").read()
    magic, dirofs, dirlen = struct.unpack("<4sii", data[:12])
    if magic != b"PACK":
        raise SystemExit("%s: not a PAK file" % path)
    lumps = {}
    for i in range(dirlen // 64):
        entry = data[dirofs + i * 64:dirofs + (i + 1) * 64]
        name = entry[:56].split(b"\0")[0].decode("latin1")
        filepos, filelen = struct.unpack("<ii", entry[56:64])
        lumps[name] = data[filepos:filepos + filelen]
    return lumps


def read_wad_lump(wad, wanted):
    if wad[:4] != b"WAD2":
        raise SystemExit("gfx.wad: not a WAD2 file")
    numlumps = struct.unpack("<i", wad[4:8])[0]
    diroffset = struct.unpack("<i", wad[8:12])[0]
    for i in range(numlumps):
        entry = wad[diroffset + i * 32:diroffset + (i + 1) * 32]
        filepos, disksize, size = struct.unpack("<iii", entry[:12])
        name = entry[16:32].split(b"\0")[0].decode("latin1")
        if name.upper() == wanted.upper():
            return wad[filepos:filepos + (disksize or size)]
    raise SystemExit("gfx.wad: lump %r not found" % wanted)


def c_array(name, blob, per_line=16):
    out = ["static const UBYTE %s[%d] = {" % (name, len(blob))]
    for i in range(0, len(blob), per_line):
        chunk = blob[i:i + per_line]
        out.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    pak_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_PAK
    out_path = os.path.abspath(sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT)

    lumps = read_pak(pak_path)
    palette = lumps.get("gfx/palette.lmp")
    conback_lmp = lumps.get("gfx/conback.lmp")
    gfxwad = lumps.get("gfx.wad")
    if palette is None or conback_lmp is None or gfxwad is None:
        raise SystemExit("PAK is missing gfx/palette.lmp, gfx/conback.lmp or gfx.wad")
    if len(palette) < 768:
        raise SystemExit("palette.lmp too small: %d" % len(palette))

    conchars = read_wad_lump(gfxwad, "conchars")
    if len(conchars) != 128 * 128:
        raise SystemExit("conchars lump size %d (want 16384)" % len(conchars))

    # conback.lmp = qpic_t {int width; int height} + width*height pixels.
    if len(conback_lmp) < 8:
        raise SystemExit("conback.lmp too small")
    cb_w, cb_h = struct.unpack("<ii", conback_lmp[:8])
    # SwapPic() in the game byteswaps these; on disk they are little-endian.
    cb_data = conback_lmp[8:]
    if cb_w * cb_h != len(cb_data):
        raise SystemExit("conback %dx%d does not match %d data bytes"
                         % (cb_w, cb_h, len(cb_data)))
    if (cb_w, cb_h) != (320, 200):
        print("warning: conback is %dx%d, expected 320x200" % (cb_w, cb_h))

    header = [
        "/* Generated by tools/extract_quake_console.py -- do not edit.",
        " * Source: %s" % os.path.basename(pak_path),
        " *   gfx/palette.lmp  crc32 %08X" % (zlib.crc32(palette) & 0xffffffff),
        " *   gfx.wad conchars crc32 %08X (%dx%d)" % (
            zlib.crc32(conchars) & 0xffffffff, 128, 128),
        " *   gfx/conback.lmp  crc32 %08X (%dx%d)" % (
            zlib.crc32(cb_data) & 0xffffffff, cb_w, cb_h),
        " *",
        " * The tests expand these exactly like BlitzQuake GL_Upload8:",
        " *  - conchars: index 0 becomes 255 (gl_draw.c:487-489);",
        " *  - d_8to24table RGB + alpha quirk (170 opaque, 255 transparent)",
        " *    (gl_vidamiga.c:239-246);",
        " *  - conback resampled 320x200 -> 256x256 via GL_ResampleTexture.",
        " */",
        "#ifndef QUAKE_CONSOLE_H_",
        "#define QUAKE_CONSOLE_H_",
        "",
        "#define QUAKE_CONSOLE_PALETTE_SIZE  768",
        "#define QUAKE_CONSOLE_CHARS_W       128",
        "#define QUAKE_CONSOLE_CHARS_H       128",
        "#define QUAKE_CONSOLE_BACK_W        %d" % cb_w,
        "#define QUAKE_CONSOLE_BACK_H        %d" % cb_h,
        "",
        c_array("g_quakePalette", palette[:768]),
        "",
        c_array("g_quakeConchars", conchars),
        "",
        c_array("g_quakeConback", cb_data),
        "",
        "#endif /* QUAKE_CONSOLE_H_ */",
        "",
    ]
    with open(out_path, "w", newline="\n") as f:
        f.write("\n".join(header))
    print("%s: palette=768 conchars=%d conback=%d bytes"
          % (out_path, len(conchars), len(cb_data)))


if __name__ == "__main__":
    main()
