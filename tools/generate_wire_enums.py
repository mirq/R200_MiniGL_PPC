#!/usr/bin/env python3
"""Generate the PPC<->68k wire translation for GL enum values.

Usage:
    generate_wire_enums.py <frontend minigl_r200.h> <native minigl_r200.h> <out.h>

Since ABI 5 the PPC R200 frontend uses OpenGL's own token values (the values
dispatch clients pass), while the 68k host and the native minigl.library are
still built against the classic numbering in
classic_68k/dev/MiniGL_Library_Source_Code/library/minigl_r200.h. Protocol 16
carries raw GL enums in a few control words (texture target/format/type,
readback format/type, bind target) and GL error codes in GL_ERROR replies, so
those words are translated at the wire, and only there.

Only the token family that actually crosses is translated: texture targets,
internal formats, pixel formats and pixel types (WIRE_TOKEN below), plus the
error codes. Everything else passes through unchanged -- in particular the
raw component counts 1..4 glTexImage2D accepts as an internalformat (3 is
also GL_LINE_STRIP), and the real-GL literals both sides already agree on
(GL_RGBA4 0x8052, GL_COLOR_INDEX8_EXT 0x80E5). A blanket table could not
work anyway: OpenGL gives GL_NO_ERROR, GL_NONE, GL_POINTS and GL_ZERO all
the value 0.
"""

import re
import sys

DEFINE = re.compile(
    r"^\s*#define\s+((?:GL|MGL)_\w+)\s+(0[xX][0-9a-fA-F]+|\d+)[uUlL]*\s*$")
# Tokens that are not GL enum values and never cross the wire as one.
SKIP = {"MGL_MAX_MODE", "GL_COLOR_BUFFER_BIT", "GL_DEPTH_BUFFER_BIT",
        "GL_TRUE", "GL_FALSE", "MGL_SM_BESTMODE"}
WIRE_TOKEN = re.compile(
    r"^(GL_(RGB|RGBA|ALPHA|LUMINANCE|INTENSITY|COLOR_INDEX|R3_G3_B2|RED|GREEN"
    r"|BLUE|BGR|BGRA|DEPTH_COMPONENT|STENCIL_INDEX)[0-9A-Z_]*"
    r"|GL_(UNSIGNED_)?(BYTE|SHORT|INT)|GL_FLOAT|GL_BITMAP"
    r"|MGL_UBYTE_[A-Z]+|MGL_UNSIGNED_SHORT_[0-9_]+|GL_TEXTURE_[123]D)$")
NOT_WIRE = {"GL_ALPHA_TEST", "GL_ALPHA_TEST_REF", "GL_ALPHA_TEST_FUNC",
            "GL_ALPHA_BITS", "GL_RED_BITS", "GL_GREEN_BITS", "GL_BLUE_BITS",
            "GL_RGBA_MODE", "GL_INDEX_BITS", "GL_DEPTH_COMPONENT_BITS"}
ERRORS = ["GL_INVALID_ENUM", "GL_INVALID_VALUE", "GL_INVALID_OPERATION",
          "GL_STACK_OVERFLOW", "GL_STACK_UNDERFLOW", "GL_OUT_OF_MEMORY"]


def defines(path):
    values = {}
    with open(path, encoding="latin-1") as handle:
        for line in handle:
            match = DEFINE.match(line)
            if match and match.group(1) not in SKIP:
                values[match.group(1)] = int(match.group(2), 0)
    return values


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    frontend, native = defines(sys.argv[1]), defines(sys.argv[2])
    pairs = sorted((frontend[n], native[n], n) for n in frontend
                   if n in native and WIRE_TOKEN.match(n) and n not in NOT_WIRE)

    # Both directions must be functions: one value per key on each side.
    for side, index in (("frontend", 0), ("native", 1)):
        seen = {}
        for pair in pairs:
            other = seen.setdefault(pair[index], pair)
            if other[1 - index] != pair[1 - index]:
                raise SystemExit(f"{side} value {pair[index]:#x} maps two ways: "
                                 f"{other[2]} and {pair[2]}")
    for name in ERRORS:
        if name not in frontend or name not in native:
            raise SystemExit(f"error code {name} missing from a header")

    out = ["/* Generated by tools/generate_wire_enums.py -- do not edit. */",
           "/*",
           " * OpenGL token values (PPC frontend, ABI 5) <-> the classic numbering the",
           " * 68k host and native minigl.library are built with. Used only where",
           " * protocol 16 carries a raw GL enum; see the generator for the contract.",
           " */",
           "#ifndef R200_WIRE_ENUM_H",
           "#define R200_WIRE_ENUM_H",
           "",
           "static GLenum WireEnumToNative(GLenum value)",
           "{",
           "    switch (value) {"]
    emitted = set()
    for gl, nat, name in pairs:
        if gl in emitted:
            continue
        emitted.add(gl)
        if gl != nat:
            out.append(f"    case 0x{gl:04X}U: return {nat}U; /* {name} */")
    out += ["    default: return value;", "    }", "}", "",
            "/* A native GL error code from a GL_ERROR reply, as the OpenGL value;",
            " * 0 when the word is not an error code at all (a handler that fails",
            " * without writing value[0] leaves the request's word there). */",
            "static GLenum WireNativeErrorToGL(GLenum native)",
            "{",
            "    switch (native) {"]
    for name in ERRORS:
        out.append(f"    case {native[name]}U: return 0x{frontend[name]:04X}U; /* {name} */")
    out += ["    default: return 0;", "    }", "}", "", "#endif", ""]
    with open(sys.argv[3], "w", encoding="ascii") as handle:
        handle.write("\n".join(out))
    print(f"{sys.argv[3]}: {len(pairs)} paired tokens")


if __name__ == "__main__":
    main()
