#!/usr/bin/env python3
"""Generate the display-list recording thunks and replay switch.

Usage:
    generate_list_thunks.py <minigl_dispatch.h> <out.c>

Display lists (ppc_common/minigl_ppc_lists.c) work by swapping the
compilable slots of the DLL's own dispatch table for recording thunks between
glNewList and glEndList; clients re-read every slot on each call, so nothing
outside compilation pays for it. Each thunk has to match its slot's exact
signature, so they are generated from the table declaration rather than
written by hand. RECORDED below is the set of compilable slots; everything
else (queries, client state, pixel store, context management, glFinish/
glFlush, texture object creation) is executed immediately, as GL 1.1
specifies. The array draws (glArrayElement/glDrawArrays/glDrawElements/
glMultiDrawArrays) and glCallList are compiled by hand in minigl_ppc_lists.c.

Encoding (locals lw/lr, so no parameter name can shadow them): one ULONG header word (opcode | payload words << 16), then the
arguments -- integers and floats one word each, doubles two words, and
pointer arguments copied inline with the element count POINTERS gives.
"""

import re
import sys

# Slots compiled into a list, in opcode order. Opcode 0 is reserved.
RECORDED = [
    "GLBegin", "GLEnd",
    "GLVertex2fv", "GLVertex3fv", "GLVertex4f", "GLVertex4fv",
    "GLColor3fv", "GLColor3ubv", "GLColor4f", "GLColor4fv", "GLColor4ub",
    "GLColor4ubv",
    "GLNormal3f", "GLNormal3fv",
    "GLTexCoord2f", "GLTexCoord2fv", "GLTexCoord4f", "GLTexCoord4fv",
    "GLMultiTexCoord2fARB", "GLMultiTexCoord2fvARB",
    "GLEdgeFlag", "GLEdgeFlagv",
    "GLActiveTextureARB", "GLAlphaFunc", "GLBindTexture", "GLBlendFunc",
    "GLBlendEquation", "GLBlendFuncSeparate",
    "GLClear", "GLClearColor", "GLClearDepth", "GLColorMask", "GLCullFace",
    "GLDepthFunc", "GLDepthMask", "GLDepthRange", "GLDrawBuffer",
    "GLFogf", "GLFogfv", "GLFrontFace", "GLHint",
    "GLLoadIdentity", "GLLoadMatrixd", "GLLoadMatrixf", "GLMatrixMode",
    "GLMultMatrixd", "GLMultMatrixf", "GLOrtho", "GLFrustum",
    "GLPopMatrix", "GLPushMatrix", "GLRotated", "GLRotatef", "GLRotatefEXT",
    "GLRotatefEXTs", "GLScaled", "GLScalef", "GLTranslated", "GLTranslatef",
    "GLPointSize", "GLLineWidth", "GLPolygonMode", "GLPolygonOffset",
    "GLScissor", "GLShadeModel", "GLViewport",
    "GLTexEnvi", "GLTexEnvfv", "GLTexGeni", "GLTexGenfv", "GLTexParameteri",
    "MGLSetState",
    "GLLightf", "GLLightfv", "GLMaterialf", "GLMaterialfv", "GLLightModelf",
    "GLLightModelfv", "GLColorMaterial",
    "GLULookAt", "GLUPerspective",
]

# Element type and count (a C expression over the parameters) for every
# pointer argument of a recorded slot.
POINTERS = {
    "GLVertex2fv": ("f", "2"), "GLVertex3fv": ("f", "3"),
    "GLVertex4fv": ("f", "4"), "GLColor3fv": ("f", "3"),
    "GLColor4fv": ("f", "4"), "GLColor3ubv": ("b", "3"),
    "GLColor4ubv": ("b", "4"), "GLNormal3fv": ("f", "3"),
    "GLTexCoord2fv": ("f", "2"), "GLTexCoord4fv": ("f", "4"),
    "GLMultiTexCoord2fvARB": ("f", "2"), "GLEdgeFlagv": ("w", "1"),
    "GLFogfv": ("f", "ListFogCount(pname)"),
    "GLLoadMatrixd": ("d", "16"), "GLMultMatrixd": ("d", "16"),
    "GLLoadMatrixf": ("f", "16"), "GLMultMatrixf": ("f", "16"),
    "GLTexEnvfv": ("f", "ListTexEnvCount(pname)"),
    "GLTexGenfv": ("f", "4"),
    "GLLightfv": ("f", "ListLightCount(pname)"),
    "GLMaterialfv": ("f", "ListMaterialCount(pname)"),
    "GLLightModelfv": ("f", "ListLightModelCount(pname)"),
}

FLOAT = {"GLfloat", "GLclampf"}
DOUBLE = {"GLdouble", "GLclampd"}
WORD = {"GLenum", "GLint", "GLuint", "GLsizei", "GLboolean", "GLbitfield",
        "GLubyte", "GLshort", "GLushort", "int", "unsigned int"}


def split_args(text):
    out, depth, cur = [], 0, ""
    for ch in text:
        depth += ch in "(["
        depth -= ch in ")]"
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return [] if out == ["void"] else out


def parse(path):
    text = open(path, encoding="latin-1").read()
    body = re.search(r"typedef struct MGLDispatchTable\s*\{(.*?)\}\s*MGLDispatchTable;",
                     text, re.S).group(1)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    fields = {}
    for line in body.splitlines():
        m = re.match(r"\s*(.+?)\(\*(\w+)\)\((.*)\);\s*$", line)
        if m:
            fields[m.group(2)] = (m.group(1).strip(), split_args(m.group(3)))
    return fields


def param(decl):
    m = re.match(r"(.*?)(\w+)$", decl.strip())
    ctype = " ".join(m.group(1).replace("const", "").split())
    return ctype, m.group(2), "*" in ctype


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    fields = parse(sys.argv[1])
    out = ["/* Generated by tools/generate_list_thunks.py -- do not edit. */",
           "/* Included by ppc_common/minigl_ppc_lists.c only. */", ""]
    enum = ["enum ListOpcode {", "    LIST_OP_NONE = 0,"]
    thunks, replay, install = [], [], []

    for name in RECORDED:
        if name not in fields:
            raise SystemExit(f"recorded slot {name} is not in the dispatch table")
        ret, args = fields[name]
        if ret != "void":
            raise SystemExit(f"recorded slot {name} returns {ret}")
        op = "LIST_OP_" + name.upper()
        enum.append(f"    {op},")
        has_ctx = bool(args) and args[0].startswith("GLcontext ")
        params = args[1:] if has_ctx else args
        sig = ", ".join(args) if args else "void"

        size_terms, stores, loads, call_args = [], [], [], []
        decls = []
        for decl in params:
            ctype, pname, is_ptr = param(decl)
            if is_ptr:
                if name not in POINTERS:
                    raise SystemExit(f"{name}: pointer {pname} has no count")
                kind, count = POINTERS[name]
                words = {"f": f"({count})", "b": f"({count})", "w": f"({count})",
                         "d": f"(2UL * ({count}))"}[kind]
                size_terms.append(words)
                stores.append(f"    lw = ListStore_{kind}(lw, {pname}, {count});")
                elem = {"f": "GLfloat", "b": "GLubyte", "w": "GLboolean",
                        "d": "GLdouble"}[kind]
                # Replay buffer: the literal count, or 4 -- the most any
                # pname-dependent vector (colours, positions) carries.
                cnt = count if count.isdigit() else "4"
                decls.append(f"            {elem} {pname}_buf[{cnt}];")
                loads.append(f"            lr = ListLoad_{kind}(lr, {pname}_buf, {count});")
                call_args.append(f"{pname}_buf")
            elif ctype in FLOAT:
                size_terms.append("1")
                stores.append(f"    lw = ListStoreFloat(lw, {pname});")
                decls.append(f"            GLfloat {pname};")
                loads.append(f"            lr = ListLoadFloat(lr, &{pname});")
                call_args.append(pname)
            elif ctype in DOUBLE:
                size_terms.append("2")
                stores.append(f"    lw = ListStoreDouble(lw, {pname});")
                decls.append(f"            GLdouble {pname};")
                loads.append(f"            lr = ListLoadDouble(lr, &{pname});")
                call_args.append(pname)
            elif ctype in WORD:
                size_terms.append("1")
                stores.append(f"    *lw++ = (ULONG){pname};")
                decls.append(f"            {ctype} {pname};")
                loads.append(f"            {pname} = ({ctype})*lr++;")
                call_args.append(pname)
            else:
                raise SystemExit(f"{name}: unhandled parameter type {ctype!r}")

        size = " + ".join(size_terms) if size_terms else "0"
        fwd_args = ", ".join(([ "context"] if has_ctx else []) +
                             [param(d)[1] for d in params])
        null_guard = ""
        pointers = [param(d)[1] for d in params if param(d)[2]]
        if pointers:
            null_guard = "    if (" + " || ".join(f"!{p}" for p in pointers) + \
                         ") {\n        ListReal." + name + f"({fwd_args});\n        return;\n    }}\n"
        body = [f"static void ListRec_{name}({sig})", "{", "    ULONG *lw;"]
        if null_guard:
            body.append(null_guard.rstrip("\n"))
        body += [f"    lw = ListAppend({op}, {size});",
                 "    if (lw) {"]
        body += ["    " + s for s in stores]
        body += ["    }",
                 "    if (ListExecuting())",
                 f"        ListReal.{name}({fwd_args});",
                 "}"]
        thunks.append("\n".join(body))

        rcall = ", ".join((["context"] if has_ctx else []) + call_args)
        case = [f"        case {op}: {{"] + decls + loads + \
               [f"            ListReal.{name}({rcall});", "            break;", "        }"]
        replay.append("\n".join(case))
        install.append(f"    table->{name} = ListRec_{name};")

    enum.append("    LIST_OP_FIRST_MANUAL")
    enum.append("};")
    out += enum + [""] + thunks + [""]
    out += ["/* Replays one generated opcode; returns the next word or NULL for an",
            " * opcode this switch does not own. */",
            "static const ULONG *ListReplayGenerated(GLcontext context, ULONG op,",
            "                                        const ULONG *lr)",
            "{",
            "    (void)context;",
            "    switch (op) {"] + replay + \
           ["    default:", "        return NULL;", "    }", "    return lr;", "}", "",
            "static void ListInstallGenerated(MGLDispatchTable *table)",
            "{"] + install + ["}", ""]
    with open(sys.argv[2], "w", encoding="ascii") as handle:
        handle.write("\n".join(out))
    print(f"{sys.argv[2]}: {len(RECORDED)} recorded slots")


if __name__ == "__main__":
    main()
