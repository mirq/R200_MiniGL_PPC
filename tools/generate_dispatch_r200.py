#!/usr/bin/env python3
"""Generate library/dispatch_table_r200.c from the MGLDispatchTable declaration.

The R200 backend keeps MiniGL's historic implicit-current-context model: its
public entry points are named Lib_gl*/Lib_mgl* and take no context argument,
because CurrentContext() resolves the calling task's context internally. Every
MGLDispatchTable field, by contrast, passes the context explicitly. This script
emits the thunk layer between the two.

Usage:
    generate_dispatch_r200.py <minigl_dispatch.h> <symbols.txt> <output.c>

<symbols.txt> is the list of Lib_* entry points the backend actually defines,
one per line, as produced by:

    m68k-amigaos-nm --defined-only obj/minigl_r200.o \\
        | sed -n 's/.* T _\\(Lib_.*\\)/\\1/p' | sort

Fields with no matching backend entry point become typed stubs that call
LibUnsupported(), which raises GL_INVALID_OPERATION exactly as the retired
186-vector table did for the same functions.
"""

import re
import sys

# Fields whose bodies cannot be derived mechanically.
SPECIAL = {
    # ABI v3 has no GLEnable/GLDisable slots; the SDK folds both into
    # MGLSetState, and the client-side glEnable/glDisable inlines call it.
    "MGLSetState": (
        ["Lib_glEnable", "Lib_glDisable"],
        "void Lib_glEnable(GLenum cap);\nvoid Lib_glDisable(GLenum cap);",
        "static void R200_MGLSetState(GLcontext context, GLenum cap, GLboolean state)\n"
        "{\n"
        "    (void)context;\n"
        "    if (state)\n"
        "        Lib_glEnable(cap);\n"
        "    else\n"
        "        Lib_glDisable(cap);\n"
        "}",
    ),
    # These are intentional WarpOS ABI-v3 compatibility behaviours. They are
    # not missing R200 backend functions and must not raise GL errors.
    "GLClientActiveTextureARB": (
        [],
        "",
        "static void R200_GLClientActiveTextureARB(GLcontext context, GLenum unit)\n"
        "{\n"
        "    (void)context;\n"
        "    (void)unit;\n"
        "}",
    ),
    "MGLResizeContext": (
        [],
        "",
        "static void R200_MGLResizeContext(GLcontext context, GLsizei width, GLsizei height)\n"
        "{\n"
        "    (void)context;\n"
        "    (void)width;\n"
        "    (void)height;\n"
        "}",
    ),
    "GLMultiDrawArrays": (
        ["Lib_glDrawArrays"],
        "void Lib_glDrawArrays(GLenum mode, GLint first, GLsizei count);",
        "static void R200_GLMultiDrawArrays(GLcontext context, GLenum mode,\n"
        "    const GLint *first, const GLsizei *count, GLsizei primcount)\n"
        "{\n"
        "    GLsizei index;\n"
        "    (void)context;\n"
        "    if (!first || !count || primcount <= 0)\n"
        "        return;\n"
        "    for (index = 0; index < primcount; ++index)\n"
        "        if (count[index] > 0)\n"
        "            Lib_glDrawArrays(mode, first[index], count[index]);\n"
        "}",
    ),
    "MGLForceNewRenderPass": (
        [],
        "",
        "static void R200_MGLForceNewRenderPass(GLcontext context)\n"
        "{\n"
        "    (void)context;\n"
        "}",
    ),
}

PREAMBLE = '''/* Generated by tools/generate_dispatch_r200.py -- do not edit. */
/*
 * Binds the R200 backend's Lib_* entry points into the V10 single-LVO
 * dispatch table.
 *
 * This file must NOT include library/minigl_r200.h: that header carries the
 * backend's own self-contained GL typedefs and enum macros, which collide with
 * mgl/gl.h. The Lib_* prototypes below are therefore restated in terms of the
 * SDK types. The two sets of typedefs are defined identically (GLboolean and
 * GLenum are unsigned int, GLsizei is long, GLbitfield is unsigned long), so
 * every thunk is a plain pass-through with no conversion.
 */
#define MINIGL_LIBRARY_BUILD 1
#include <exec/types.h>
#include <libraries/minigl_dispatch.h>
#include "context_access.h"

/* Raises GL_INVALID_OPERATION on the current context; see minigl_r200.c. */
ULONG LibUnsupported(void);

'''


def split_args(text):
    """Split a C parameter list on top-level commas."""
    args, depth, current = [], 0, ""
    for ch in text:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            args.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        args.append(current.strip())
    return args


def arg_name(arg):
    """Extract the parameter name from a C parameter declaration."""
    match = re.search(r"(\w+)\s*(\[\s*\])?$", arg)
    if not match:
        raise SystemExit(f"unnamed parameter in dispatch table: {arg!r}")
    return match.group(1)


def parse_fields(header_text):
    body = re.search(
        r"typedef struct MGLDispatchTable\s*\{(.*?)\}\s*MGLDispatchTable;",
        header_text,
        re.S,
    )
    if not body:
        raise SystemExit("could not locate the MGLDispatchTable declaration")

    fields = []
    for line in body.group(1).splitlines():
        match = re.match(r"\s*(.+?)\(\*(\w+)\)\((.*)\);\s*$", line)
        if match:
            ret, name, args = match.groups()
            parsed = split_args(args)
            if parsed == ["void"]:  # an explicit (void) is not a parameter
                parsed = []
            fields.append((ret.strip(), name, parsed))
    return fields


def candidates(field):
    """Backend entry-point names this dispatch field could bind to."""
    if field == "StubPolygonOffset":
        return ["Lib_glPolygonOffset"]
    if field.startswith("Direct_mgl"):
        return ["Lib_" + field[len("Direct_"):]]
    if field.startswith("GL"):
        # Both spellings are tried, because GLULookAt maps to Lib_gluLookAt
        # while GLUnlockArrays maps to Lib_glUnlockArrays.
        return ["Lib_gl" + field[2:], "Lib_glu" + field[3:]]
    if field.startswith("MGL"):
        return ["Lib_mgl" + field[3:]]
    if field.startswith("mgl"):
        return ["Lib_" + field]
    return []


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)

    header_path, symbols_path, out_path = sys.argv[1:4]

    with open(header_path, encoding="ascii") as handle:
        fields = parse_fields(handle.read())
    with open(symbols_path, encoding="ascii") as handle:
        available = {line.strip() for line in handle if line.strip()}

    externs, thunks, entries, unsupported = [], [], [], []

    # Entries overridable by the dispatcher. GLTexImage2D/glTexSubImage2D
    # have more than eight arguments, where the PowerOpen ABI (vbcc/WarpOS
    # clients) and the SysV ABI (this GCC-built DLL) disagree on stack
    # argument locations; the R200 dispatcher replaces these two table
    # slots with ABI-bridging assembly trampolines.
    OVERRIDABLE_ENTRIES = {
        "GLTexImage2D": "R200_TABLE_GLTexImage2D",
        "GLTexSubImage2D": "R200_TABLE_GLTexSubImage2D",
    }

    for ret, name, args in fields:
        if name in SPECIAL:
            _, extern, thunk = SPECIAL[name]
            externs.append(extern)
            thunks.append(thunk)
            entries.append("R200_" + name)
            continue

        target = next((c for c in candidates(name) if c in available), None)
        drops_context = bool(args) and args[0].startswith("GLcontext ")
        passed = args[1:] if drops_context else args
        params = ", ".join(args) if args else "void"

        if target:
            decl_args = ", ".join(passed) if passed else "void"
            externs.append(f"{ret} {target}({decl_args});")

            call = f"{target}({', '.join(arg_name(a) for a in passed)})"
            body = "    (void)context;\n" if drops_context else ""
            body += f"    {'return ' if ret != 'void' else ''}{call};"
            thunks.append(f"static {ret} R200_{name}({params})\n{{\n{body}\n}}")
            entries.append(OVERRIDABLE_ENTRIES.get(name, "R200_" + name))
            continue

        # No backend implementation: raise GL_INVALID_OPERATION and return zero.
        unsupported.append(name)
        discards = "".join(f"    (void){arg_name(a)};\n" for a in args)
        body = discards + "    LibUnsupported();\n"
        if ret != "void":
            body += f"    return ({ret})0;\n"
        thunks.append(
            f"static {ret} R200Unsupported_{name}({params})\n{{\n{body}}}"
        )
        entries.append("R200Unsupported_" + name)

    out = [PREAMBLE]
    out.append("/* Backend entry points, restated in SDK types. */\n")
    out.append("\n".join(dict.fromkeys(externs)))
    out.append("\n\n")
    out.append(
        f"/* {len(unsupported)} fields the R200 backend does not implement:\n"
        + "\n".join(f" *   {n}" for n in unsupported)
        + "\n */\n\n"
    )
    out.append("\n\n".join(thunks))
    out.append(
        "\n\n/* Overridable ABI-bridge slots (see OVERRIDABLE_ENTRIES). */\n"
        "#ifndef R200_TABLE_GLTexImage2D\n"
        "#define R200_TABLE_GLTexImage2D R200_GLTexImage2D\n"
        "#endif\n"
        "#ifndef R200_TABLE_GLTexSubImage2D\n"
        "#define R200_TABLE_GLTexSubImage2D R200_GLTexSubImage2D\n"
        "#endif\n"
    )
    out.append("\nconst MGLDispatchTable MiniGLDispatchTable = {\n")
    out.append("    MINIGL_DISPATCH_ABI_VERSION,\n")
    out.append("    (ULONG)sizeof(MGLDispatchTable),\n")
    out.append("    MINIGL_BACKEND_FLAG_R200,\n")
    out.append("    0,\n")
    out.append("    &mini_CurrentContext,\n")
    out.extend(f"    {entry},\n" for entry in entries)
    out.append("};\n")

    with open(out_path, "w", encoding="ascii") as handle:
        handle.write("".join(out))

    print(
        f"{out_path}: {len(entries)} fields, "
        f"{len(entries) - len(unsupported)} bound, "
        f"{len(unsupported)} unsupported"
    )


if __name__ == "__main__":
    main()
