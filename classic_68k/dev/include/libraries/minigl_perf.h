/*
 * Worst-frame attribution (rank-ordered slowest frames, 10 slots each).
 * RECONSTRUCTED 2026-09-03: the PiStorm_SDK_v10 staging copy of this
 * header carried the original values and was lost in an include-tree
 * sync; these are fresh values, spaced so each 10-slot range can never
 * collide, consistent across the dev tree and the SDK staging copy.
 * The SDK-lineage backend tracks and answers these; backends without
 * worst-frame tracking must answer 0 (see Lib_glGetIntegerv).
 */
#define MGL_PERF_WORST_SLOTS 10UL
#define MGL_PERF_WORST_FRAME_NUMBER_BASE 0x7f200050UL
#define MGL_PERF_WORST_FRAME_NUMBER(index) \
    (MGL_PERF_WORST_FRAME_NUMBER_BASE + (GLenum)(index))
#define MGL_PERF_WORST_FRAME_TICKS_BASE 0x7f200060UL
#define MGL_PERF_WORST_FRAME_TICKS(index) \
    (MGL_PERF_WORST_FRAME_TICKS_BASE + (GLenum)(index))
